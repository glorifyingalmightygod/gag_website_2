  <!-- Theological Themes -->
  <div class="bk-section">
    <div class="bk-section-header"><h3>&#9884; Theological Themes</h3></div>
    <div class="bk-section-body">
      <p><strong>The Davidic Covenant (2 Samuel 7):</strong> The most theologically significant passage in the book. God promises David an eternal dynasty, an eternal throne, and an eternal kingdom — unconditionally. This becomes the foundation of Messianic expectation fulfilled in Jesus Christ (Luke 1:32–33).</p>
      <p><strong>Divine Discipline:</strong> God's love includes discipline. Nathan's prophecy in chapter 12 is fulfilled through the sword never departing from David's house — demonstrating that forgiveness does not cancel earthly consequences.</p>
      <p><strong>Grace:</strong> David's treatment of Mephibosheth (chapter 9) is one of the Old Testament's most beautiful pictures of God's undeserved kindness toward the broken and helpless.</p>
      <p><strong>Repentance:</strong> David's response to Nathan's rebuke — "I have sinned against the LORD" — is one of Scripture's clearest models of genuine, immediate, unconditional repentance (2 Samuel 12:13; Psalm 51).</p>
      <p><strong>Worship and Holiness:</strong> The Ark narratives (chapters 6) establish that approaching God demands reverence. David's insistence on costly sacrifice in chapter 24 affirms that true worship is never casual or cheap.</p>
    </div>
  </div>

