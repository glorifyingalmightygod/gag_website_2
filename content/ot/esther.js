      <p class="bk-shadow-body">The Feast of Purim was established so that no generation of Jews would forget their deliverance from death (Esther 9:26–28). Christ instituted the Lord's Supper for the same reason — "Do this in remembrance of Me" — so that no believer would forget their deliverance from sin and death through His sacrifice. Both feasts celebrate a people rescued from destruction through an intercessor's sacrifice (Luke 22:19; 1 Corinthians 11:24–26).</p>
