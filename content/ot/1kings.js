  <!-- Author -->
  <div class="bk-section">
    <div class="bk-section-header"><h3>&#9997; Author of the Book</h3></div>
    <div class="bk-section-body">
      <p><strong>Traditional Author:</strong> Jewish tradition (including the Talmud) attributes authorship to the prophet Jeremiah. The language, themes, and theological emphasis align closely with Jeremiah's writings.</p>
      <p><strong>Internal Evidence:</strong> Strong emphasis on covenant obedience and judgment, similar language to Deuteronomy and Jeremiah, and prominent attention to prophetic ministry throughout.</p>
      <p><strong>Scholarly Opinions:</strong> Modern scholars believe Kings was compiled by inspired prophetic historians — sometimes called the "Deuteronomistic Historians" — who organized royal and prophetic records, likely finalized during the Babylonian exile to explain why Israel and Judah experienced divine judgment.</p>
    </div>
  </div>

