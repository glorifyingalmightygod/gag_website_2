      <div class="bk-shadow-body">"The latter glory of this house shall be greater than the former." The immediate reference is God's future blessing on the Second Temple, but Christian interpretation has also connected the passage with Christ's presence in the temple and the greater salvation revealed through Him (Luke 2:22–38; John 2:13–22; Malachi 3:1; Hebrews 9:11–14) — a theological, canonical reading rather than a claim that every detail is a direct prediction of Jesus.</div>
