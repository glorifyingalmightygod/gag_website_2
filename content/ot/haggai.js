      <div class="bk-shadow-body">Zerubbabel, a descendant of David (Matthew 1:12–13; 1 Chronicles 3:17–19; Ezra 3:2), is called "my servant" and compared to a signet ring — recalling royal authority and Davidic covenant imagery (2 Samuel 7:12–16; Jeremiah 22:24–30). Haggai does not say Zerubbabel himself is the Messiah, but his position in the Davidic line contributes to the Old Testament's continuing messianic expectation.</div>
